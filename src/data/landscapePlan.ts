// Boundaries traced on the supplied landscape illustration, in image pixels.
// Commercial metadata and lot IDs still come from the official plan.
const paths: Record<string, string> = {};

function row(block: string, numbers: number[], top: number, bottom: number, upper: number[], lower = upper) {
  numbers.forEach((number, i) => {
    const id = block + '-' + String(number).padStart(2, '0');
    paths[id] = [
      'M' + upper[i] + ',' + top,
      'L' + upper[i + 1] + ',' + top,
      'L' + lower[i + 1] + ',' + bottom,
      'L' + lower[i] + ',' + bottom,
      'Z',
    ].join(' ');
  });
}

